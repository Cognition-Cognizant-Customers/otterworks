// Generates src/assets/dev-auth.json, the local-development bearer token the
// mocked admin login hands to admin-service. The token is signed with the
// JWT_SECRET the backend services are running with -- defaulting to the same
// local-development secret docker-compose.yml gives every service -- so nothing
// signed is ever committed and the dashboard works out of the box locally.
import { createHmac } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ADMIN_ID = 'a0000000-0000-0000-0000-000000000001';
const ADMIN_EMAIL = process.env.DEV_ADMIN_EMAIL || 'admin@otterworks.dev';
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'dev-auth.json');

const encode = value => Buffer.from(typeof value === 'string' ? value : JSON.stringify(value))
  .toString('base64url');

function sign(secret) {
  const issuedAt = 1704067200;
  const signingInput = [
    encode({ alg: 'HS256', typ: 'JWT' }),
    encode({
      sub: ADMIN_ID,
      user_id: ADMIN_ID,
      email: ADMIN_EMAIL,
      role: 'admin',
      iat: issuedAt,
      exp: issuedAt + 220838400,
    }),
  ].join('.');
  return `${signingInput}.${createHmac('sha256', secret).update(signingInput).digest('base64url')}`;
}

// Matches the local-development default in docker-compose.yml.
const secret = process.env.JWT_SECRET || 'otterworks-local-dev-jwt-secret-change-me-in-production';
mkdirSync(dirname(OUTPUT), { recursive: true });
writeFileSync(
  OUTPUT,
  `${JSON.stringify(
    {
      _comment:
        'Generated by scripts/generate-dev-auth.mjs from JWT_SECRET; local development only, never committed.',
      token: sign(secret),
    },
    null,
    2,
  )}\n`,
);
console.log(`Wrote local-development admin token to ${OUTPUT}`);
